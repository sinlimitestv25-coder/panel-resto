export const DICTS: Record<Lang, Dict> = { es, en, pt, fr, it, de };

export function t(lang: Lang, key: keyof typeof es, vars?: Record<string, string | number>) {
  let str = DICTS[lang]?.[key] ?? DICTS.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
